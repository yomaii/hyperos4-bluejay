#!/usr/bin/env python3
"""Generate config/perf/port_perf.rc from LEVELS."""
import os

# HyperOS mode -> LOW_POWER_* suffix in the Pixel powerhint.json (None = no limit)
LEVELS = {'perf': None, 'balance': 90, 'save': 70, 'super': 50}
# resulting caps in MHz (little/mid/big), for the comment only
FREQ = {None: (1803, 2253, 2802), 90: (1803, 1999, 2401), 70: (1328, 1663, 1745), 50: (930, 910, 1277)}


def hints(n):
    return [f'LOW_POWER_CPU_{n}', f'LOW_POWER_MID_CLUSTER_{n}', f'LOW_POWER_LITTLE_CLUSTER_{n}']


def main():
    all_hints = [h for n in LEVELS.values() if n for h in hints(n)]
    table = '\n'.join(f'#   {m:<9} {str(n) if n else "none":<6}' + ''.join(f'{f:>6} ' for f in FREQ[n]).rstrip()
                      for m, n in LEVELS.items())
    out = [f'''# HyperOS power-saving / performance modes -> Pixel Power HAL LOW_POWER_* hints.
# Generated by config/perf/gen_rc.py.
#
# PortPerfBridge (services.jar) sets
#   sys.port.perfmode       perf / balance / save / super
#   sys.port.perfmode.tick  bumped at boot and every 50 minutes (the hints expire after an hour)
# init -> sendhint_vendor is an existing domain transition in the Pixel policy.
#
#   mode      level   little   mid   big (MHz)
{table}
''']
    for m, n in LEVELS.items():
        own = hints(n) if n else []
        out.append(f'on property:sys.port.perfmode={m}')
        out += [f'    exec_background -- /vendor/bin/sendhint -m {h} -e 0' for h in all_hints if h not in own]
        out += [f'    exec_background -- /vendor/bin/sendhint -m {h} -e 1' for h in own]
        out.append('')
    for m, n in LEVELS.items():
        if n:
            out.append(f'on property:sys.port.perfmode.tick=* && property:sys.port.perfmode={m}')
            out += [f'    exec_background -- /vendor/bin/sendhint -m {h} -e 1' for h in hints(n)]
            out.append('')
    dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'port_perf.rc')
    with open(dst, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))
    print(f'wrote {dst}')


if __name__ == '__main__':
    main()
